from __future__ import annotations

import ast
import re
import tokenize
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[1]
_SRC = _ROOT / "src" / "damascus"
_TESTS = _ROOT / "tests"

_FORBIDDEN = [
    r"reproduction of",
    r"based on the paper",
    r"re-implementation",
    r"following the authors",
    r"as described by",
    r"generated by",
    r"ai-assisted",
    r"\bskeleton\b",
    r"\bplaceholder\b",
    r"\btodo\b",
    r"\bcomprehensive\b",
    r"\brobust\b",
    r"state-of-the-art",
    r"cutting-edge",
    r"seamlessly",
    r"\bleverag\w*",
    r"\butiliz\w*",
    r"\bdelve\b",
    r"\bholistic\b",
    r"meticulous\w*",
    r"it's worth noting",
    r"in conclusion",
]
_EMOJI = re.compile("[\U0001f000-\U0001faff\U00002600-\U000027bf\U0001f1e6-\U0001f1ff]")


def _python_files() -> list[Path]:
    files = sorted(_SRC.rglob("*.py")) + sorted(_TESTS.rglob("*.py"))
    return [path for path in files if path.name != "test_style_guard.py"]


def test_no_inline_comments() -> None:
    offenders = []
    for path in _python_files():
        with tokenize.open(path) as handle:
            for token in tokenize.generate_tokens(handle.readline):
                if token.type == tokenize.COMMENT:
                    offenders.append(f"{path.name}:{token.start[0]}")
    assert offenders == []


def test_no_docstrings() -> None:
    offenders = []
    for path in _python_files():
        tree = ast.parse(path.read_text())
        doc_nodes = (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
        for node in ast.walk(tree):
            if isinstance(node, doc_nodes) and ast.get_docstring(node) is not None:
                offenders.append(f"{path.name}:{getattr(node, 'name', 'module')}")
    assert offenders == []


def test_no_forbidden_phrases() -> None:
    scanned = _python_files() + [_ROOT / "README.md", _ROOT / "Makefile"]
    patterns = [re.compile(p, re.IGNORECASE) for p in _FORBIDDEN]
    offenders = []
    for path in scanned:
        if not path.exists():
            continue
        text = path.read_text()
        for pattern in patterns:
            if pattern.search(text):
                offenders.append(f"{path.name}:{pattern.pattern}")
    assert offenders == []


def test_no_emoji() -> None:
    scanned = _python_files() + [_ROOT / "README.md", _ROOT / "Makefile"]
    offenders = [path.name for path in scanned if path.exists() and _EMOJI.search(path.read_text())]
    assert offenders == []
